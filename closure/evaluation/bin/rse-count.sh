#!/bin/bash
# Run-time security enforcement (RSE) sites in the generated Solidity --
# the SCIF paper's Table 1 metric, split by mechanism so the closure
# additions are visible.
#
# An RSE site is an `assert(...)` whose condition uses a security
# primitive.  Library-internal sanity asserts (array lengths, bound
# masks) are not security enforcement and are excluded.
#
#   lock      bypassLocks / acquireLock / releaseLock
#   trust     trusts(...)        -- normal public entry: caller check
#   actsFor   actsFor(...)       -- closure entry: believed vs real label
#   success   assert(closureOk)  -- closure invoke: abort check
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
FR="$HERE/../../foundry-run"
python3 - "$FR" <<'PY'
import re, sys, os
fr = sys.argv[1]

# Role of each contract in the closure flow, for the variant column.
ROLE = {
    "UniswapRouter": "SCIF: closurable target",
    "Aggregator":    "SCIF: closure invoker",
    "User":          "SCIF: closure creator",
    "UserDirect":    "SCIF: no closure",
}

def sites(body):
    a = re.findall(r'assert\(([^;]*)\)\s*;', body)
    lock = sum(1 for x in a if re.search(r'\b(bypassLocks|acquireLock|releaseLock)\(', x))
    trust = sum(1 for x in a if re.search(r'\btrusts(_[0-9a-f]+)?\(', x)
                and not re.search(r'\b(bypassLocks|acquireLock|releaseLock)\(', x))
    af = sum(1 for x in a if re.search(r'\bactsFor\(', x))
    ok = sum(1 for x in a if re.search(r'closureOk', x))
    return lock, trust, af, ok

def contracts(path):
    if not os.path.exists(path):
        return []
    parts = re.split(r'^contract\s+(\w+)', open(path).read(), flags=re.M)
    return [(parts[i], parts[i + 1]) for i in range(1, len(parts), 2)]

hdr = f"{'contract':<16}{'variant':<26}{'lock':>5}{'trust':>6}{'actsFor':>8}{'success':>8}{'total':>7}"
print(hdr)
print("-" * len(hdr))

# Compiler output: every one of these is Solidity generated by SCIF.
for fn in ("full.sol", "direct.sol"):
    for name, body in contracts(os.path.join(fr, "src", fn)):
        l, t, a, o = sites(body)
        print(f"{name:<16}{ROLE.get(name, 'SCIF'):<26}{l:>5}{t:>6}{a:>8}{o:>8}{l+t+a+o:>7}")

# Hand-written baseline: not compiler output. One line; it enforces nothing.
raw = contracts(os.path.join(fr, "src", "baseline_raw.sol"))
tot = [sum(x) for x in zip(*[sites(b) for _, b in raw])] if raw else [0, 0, 0, 0]
names = ", ".join(n for n, _ in raw) if raw else "-"
print(f"{'(' + str(len(raw)) + ' contracts)':<16}{'hand-written Solidity':<26}"
      f"{tot[0]:>5}{tot[1]:>6}{tot[2]:>8}{tot[3]:>8}{sum(tot):>7}")
print()
print(f"The hand-written baseline is the unsafe calldata-relay idiom ({names});")
print("it is not compiler output and enforces nothing at run time -- that is the")
print("vulnerability closures remove. Every other row IS Solidity emitted by SCIF.")
print()
print("An RSE site is an assert() whose condition uses a security primitive.")
print("Library-internal sanity asserts (array lengths, bound masks) are excluded.")
PY
