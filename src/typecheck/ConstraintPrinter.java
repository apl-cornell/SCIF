package typecheck;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes constraints, as SHErrLoc prints them, in the terms of SCIF source code: the names the
 * type checkers generate are written as the labels, principals, variables, types and program
 * points they stand for. In constraints on labels, flows are written {@code a => b} (a is
 * trusted at least as much as b), and joins and meets {@code ⨆} and {@code ⨅}.
 */
public final class ConstraintPrinter {

    private ConstraintPrinter() {
    }

    /**
     * The constraint on labels {@code constraint}, in the form SHErrLoc prints it, written for a
     * reader of contract {@code contractName}. Text that is not in that form is returned
     * unchanged.
     */
    public static String constraint(String constraint, String contractName) {
        return render(constraint, contractName, false);
    }

    /**
     * The constraint on types {@code constraint}, in the form SHErrLoc prints it, written for a
     * reader of contract {@code contractName}. Text that is not in that form is returned
     * unchanged.
     */
    public static String typeConstraint(String constraint, String contractName) {
        return render(constraint, contractName, true);
    }

    private static String render(String constraint, String contractName, boolean types) {
        List<String> tokens = tokenize(constraint);
        if (tokens == null) {
            return constraint;
        }
        Parser parser = new Parser(tokens, contractName, types);
        try {
            String result = parser.relation();
            return parser.atEnd() ? result : constraint;
        } catch (Unrecognized e) {
            return constraint;
        }
    }

    /**
     * The name {@code name}, generated by a type checker, written for a reader of contract
     * {@code contractName}. A name that is not in a recognized form is returned unchanged.
     */
    public static String name(String name, String contractName) {
        if (name.startsWith("global.")) {
            return name.substring("global.".length());
        }
        Matcher m = QUALIFIED.matcher(name);
        if (!m.matches()) {
            return name;
        }
        String contract = m.group(1);
        String rest = m.group(2);

        String version = "";
        Matcher v = VERSION.matcher(rest);
        if (v.matches()) {
            rest = v.group(1);
            version = "#" + v.group(2);
        }
        if (rest.endsWith("..lbl")) {
            return "label(" + path(contract, rest.substring(0, rest.length() - 5), contractName)
                    + version + ")";
        }
        if (rest.endsWith("..new")) {
            return "contract created by " + point(rest.substring(0, rest.length() - 5));
        }
        if (rest.endsWith(".PC.next")) {
            return "pc after " + point(rest.substring(0, rest.length() - 8));
        }
        if (rest.endsWith(".PC")) {
            String inner = rest.substring(0, rest.length() - 3);
            return isMethod(inner) ? "pc at start of " + inner : "pc at " + point(inner);
        }
        if (rest.endsWith(".LK")) {
            return "lock after " + point(rest.substring(0, rest.length() - 3));
        }
        String[] comps = rest.split("\\.");
        if (comps.length >= 2 && !isScope(comps[0])) {
            String method = comps[0];
            String tail = String.join(".", Arrays.copyOfRange(comps, 1, comps.length));
            String described = METHOD_NAMES.get(tail);
            if (described != null) {
                return described + " " + method;
            }
        }
        if (isScope(comps[comps.length - 1])) {
            return point(rest);
        }
        return path(contract, rest, contractName) + version;
    }

    /** {@code s<file>.<contract>.<rest>}. */
    private static final Pattern QUALIFIED = Pattern.compile("s\\d+\\.([^.]+)\\.(.+)");
    /** A variable version: {@code <name>..v<n>}. */
    private static final Pattern VERSION = Pattern.compile("(.*)\\.\\.v(\\d+)");
    /** A program point: {@code <kind>L<line>C<column>s<file>}. */
    private static final Pattern SCOPE = Pattern.compile("([A-Za-z]+)L(\\d+)C(\\d+)s\\d+");

    /** Descriptions of the names a method's labels are given, keyed by their suffix. */
    private static final Map<String, String> METHOD_NAMES = Map.of(
            "extpc", "external begin label of",
            "inpc", "internal begin label of",
            "gamma", "reentrancy lock label of",
            "returnV", "label of the return value of",
            "ILK", "lock on entry to",
            "rtn.lk", "lock at end of",
            "rtn.pc", "pc at end of",
            "rtn.v", "return value of");

    /** Descriptions of the kinds of program points, keyed by their names. */
    private static final Map<String, String> KINDS = Map.ofEntries(
            Map.entry("Subscript", "element read"),
            Map.entry("struct", "member read"),
            Map.entry("Attribute", "member read"),
            Map.entry("Call", "call"),
            Map.entry("CallStatement", "statement"),
            Map.entry("Name", "name"),
            Map.entry("New", "new"),
            Map.entry("ExceptHandler", "handler"),
            Map.entry("GuardBlock", "lock block"),
            Map.entry("guardBlock", "lock block"),
            Map.entry("lock", "lock block"),
            Map.entry("endorseIf", "endorse-if"),
            Map.entry("EndorseIfStatement", "endorse-if"),
            Map.entry("AnnAssign", "declaration"),
            Map.entry("Assign", "assignment"),
            Map.entry("ArrayOperation", "array operation"),
            Map.entry("BinOp", "operation"),
            Map.entry("bin", "operation"),
            Map.entry("BoolOp", "operation"),
            Map.entry("UnaryOp", "operation"),
            Map.entry("Compare", "comparison"),
            Map.entry("closure", "closure"),
            Map.entry("ClosureCreation", "closure"));

    private static String lastComponent(String name) {
        return name.substring(name.lastIndexOf('.') + 1);
    }

    private static boolean isScope(String comp) {
        return SCOPE.matcher(comp).matches();
    }

    private static boolean isMethod(String inner) {
        return !inner.contains(".") && !isScope(inner);
    }

    /**
     * The innermost program point named in {@code inner}, a dot-separated path ending in or
     * containing program points.
     */
    private static String point(String inner) {
        String[] comps = inner.split("\\.");
        for (int i = comps.length - 1; i >= 0; --i) {
            Matcher m = SCOPE.matcher(comps[i]);
            if (m.matches()) {
                String kind = KINDS.getOrDefault(m.group(1), m.group(1).toLowerCase());
                return kind + " " + m.group(2) + ":" + m.group(3);
            }
        }
        return inner;
    }

    /**
     * The variable or principal named by {@code inner} in contract {@code contract}: a field
     * or principal of the contract, or a local variable (or member of one) of one of its
     * methods, whose name starts with the method's.
     */
    private static String path(String contract, String inner, String contractName) {
        List<String> comps = new ArrayList<>();
        for (String comp : inner.split("\\.")) {
            if (!comp.isEmpty() && !isScope(comp)) {
                comps.add(comp);
            }
        }
        if (comps.size() == 1) {
            String n = comps.get(0);
            boolean ours = contract.equals(contractName);
            if (n.equals(Utils.LABEL_TOP)) {
                return ours ? "this" : contract + ".this";
            }
            return ours ? n : contract + "." + n;
        }
        // A local name: drop the method's name.
        return String.join(".", comps.subList(1, comps.size()));
    }

    /**
     * The tokens of {@code constraint}: parentheses, the relations {@code <=}, {@code ==} and
     * {@code >=}, the operators {@code join} and {@code meet}, and names; or null if it
     * contains anything else.
     */
    private static List<String> tokenize(String constraint) {
        List<String> tokens = new ArrayList<>();
        Matcher m = TOKEN.matcher(constraint);
        int at = 0;
        while (at < constraint.length()) {
            if (Character.isWhitespace(constraint.charAt(at))) {
                ++at;
                continue;
            }
            if (!m.find(at) || m.start() != at) {
                return null;
            }
            tokens.add(m.group());
            at = m.end();
        }
        return tokens;
    }

    /** Thrown when a constraint's tokens are not in the expected form. */
    private static final class Unrecognized extends Exception {
    }

    private static final Pattern TOKEN = Pattern.compile("[()]|<=|==|>=|[^\\s()<=>]+");

    /** A parser for {@code relation := lattice (relop lattice)?}. */
    private static final class Parser {
        private final List<String> tokens;
        private final String contractName;
        private final boolean types;
        private int pos = 0;

        Parser(List<String> tokens, String contractName, boolean types) {
            this.tokens = tokens;
            this.contractName = contractName;
            this.types = types;
        }

        boolean atEnd() {
            return pos == tokens.size();
        }

        private String peek() {
            return atEnd() ? null : tokens.get(pos);
        }

        String relation() throws Unrecognized {
            Term left = lattice();
            String op = peek();
            if (op == null || !(op.equals("<=") || op.equals("==") || op.equals(">="))) {
                return left.text;
            }
            ++pos;
            Term right = lattice();
            if (types) {
                return left.text + (op.equals("==") ? " = " : " " + op + " ") + right.text;
            }
            return switch (op) {
                case "<=" -> left.text + " => " + right.text;
                case ">=" -> right.text + " => " + left.text;
                default -> left.text + " = " + right.text;
            };
        }

        /** A rendered term, and the lattice operator at its top, if any. */
        private record Term(String text, String op) {
        }

        private Term lattice() throws Unrecognized {
            List<Term> operands = new ArrayList<>();
            operands.add(primary());
            String op = null;
            while ("join".equals(peek()) || "meet".equals(peek())) {
                String next = tokens.get(pos++);
                if (op != null && !op.equals(next)) {
                    // Mixed operators: group what came before.
                    Term grouped = combine(operands, op);
                    operands = new ArrayList<>(List.of(grouped));
                }
                op = next;
                operands.add(primary());
            }
            return op == null ? operands.get(0) : combine(operands, op);
        }

        private static Term combine(List<Term> operands, String op) {
            String symbol = op.equals("join") ? " ⨆ " : " ⨅ ";
            List<String> parts = new ArrayList<>();
            for (Term t : operands) {
                parts.add(t.op == null || t.op.equals(op) ? t.text : "(" + t.text + ")");
            }
            return new Term(String.join(symbol, parts), op);
        }

        private Term primary() throws Unrecognized {
            String t = peek();
            if (t == null || t.equals(")") || t.equals("<=") || t.equals("==") || t.equals(">=")) {
                throw new Unrecognized();
            }
            ++pos;
            if (t.equals("(")) {
                Term inner = lattice();
                if (!")".equals(peek())) {
                    throw new Unrecognized();
                }
                ++pos;
                return inner;
            }
            String n = name(t, contractName);
            // In a constraint on types, a program point stands for the type of its value.
            return new Term(types && !n.equals(t) && SCOPE.matcher(lastComponent(t)).matches()
                    ? "type of " + n : n, null);
        }
    }
}
